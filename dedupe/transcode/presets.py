def get_preset(preset_id: str) -> TranscodePreset:
    try:
        return PRESETS[preset_id]
    except KeyError as exc:
        choices = ", ".join(PRESETS)
        raise ValueError(f"Unknown preset '{preset_id}'. Available presets: {choices}") from exc
